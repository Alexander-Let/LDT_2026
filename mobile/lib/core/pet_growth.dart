/// Рост питомца (ТЗ 2.5.10 «Прогресс питомца»: ≥3 стадий, зависит от
/// совокупности решений ребёнка, с кратким объяснением причины).
///
/// Формула: стадия зависит от числа ПРОЙДЕННЫХ этапов «Дорожки знаний»
/// (пройденный этап = серия решений: уроки, покупки, пополнения копилки):
///   0–1 этапов  → стадия 1 (малыш, без украшения);
///   2–3 этапа   → стадия 2 (красный шарфик assets/pet/tap2.svg);
///   4–5 этапов  → стадия 3 (праздничный воротничок assets/pet/tap3.svg).
library;

/// Стадия роста по числу завершённых этапов дорожки (1..3).
int growthStage(int stagesCompleted) {
  if (stagesCompleted >= 4) return 3;
  if (stagesCompleted >= 2) return 2;
  return 1;
}

/// Элемент на шее для стадии (null — первая стадия, без украшения).
String? growthNeckAsset(int stage) => switch (stage) {
      2 => 'assets/pet/tap2.svg',
      3 => 'assets/pet/tap3.svg',
      _ => null,
    };

/// Краткое объяснение причины роста — простым языком (ТЗ 2.5.10).
String growthExplanation(int stage) => switch (stage) {
      2 =>
        'Ты прошёл уже два этапа дорожки: кормил питомца, копил монетки и '
            'делал умные выборы — поэтому Финни подрос и получил шарфик!',
      3 =>
        'Целых четыре этапа пройдено! Ты настоящий финансовый гуру, '
            'и Финни вырос большой и праздничный!',
      _ => 'Проходи этапы дорожки — и Финни будет расти!',
    };
